-- 校园活动（A1）：认证组织者发布，本校学生报名；签到与发奖在后续迁移补充。
CREATE TABLE activities (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    school_id BIGINT NOT NULL,
    organizer_id BIGINT NOT NULL,
    organizer_name VARCHAR(80) NOT NULL COMMENT '主办方展示名，如「计算机学院学生会」',
    title VARCHAR(80) NOT NULL,
    category VARCHAR(20) NOT NULL COMMENT 'LECTURE/COMPETITION/VOLUNTEER/SPORTS/CULTURE/CLASS/OTHER',
    cover_url VARCHAR(500) NULL,
    description TEXT NOT NULL,
    notice VARCHAR(1000) NULL COMMENT '报名须知',
    location VARCHAR(120) NOT NULL,
    starts_at DATETIME NOT NULL,
    ends_at DATETIME NOT NULL,
    signup_deadline DATETIME NOT NULL,
    audience_scope VARCHAR(10) NOT NULL COMMENT 'SCHOOL/COLLEGE/MAJOR：谁可以报名；本校所有人都能看到',
    audience_college_id BIGINT NULL,
    audience_major_id BIGINT NULL,
    audience_entry_year SMALLINT NULL COMMENT '可选：只限某一级',
    capacity INT NULL COMMENT '为空表示不限名额',
    waitlist_enabled TINYINT(1) NOT NULL DEFAULT 1,
    reward_xp INT NOT NULL DEFAULT 0,
    reward_coins INT NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'PUBLISHED' COMMENT 'PUBLISHED/CANCELLED；报名中/进行中等阶段由时间计算',
    registered_count INT NOT NULL DEFAULT 0,
    waitlist_count INT NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    KEY idx_activities_school_start (school_id, status, starts_at, id),
    KEY idx_activities_organizer (organizer_id, created_at),
    CONSTRAINT fk_activities_school FOREIGN KEY (school_id) REFERENCES schools(id),
    CONSTRAINT fk_activities_organizer FOREIGN KEY (organizer_id) REFERENCES users(id)
);

CREATE TABLE activity_registrations (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    activity_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL COMMENT 'REGISTERED/WAITLISTED/CANCELLED',
    queued_at DATETIME(6) NOT NULL COMMENT '本次报名时间，候补按它递补',
    cancelled_at DATETIME NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uk_activity_registrations_user (activity_id, user_id),
    KEY idx_activity_registrations_queue (activity_id, status, queued_at, id),
    KEY idx_activity_registrations_user (user_id, status, activity_id),
    CONSTRAINT fk_activity_registrations_activity FOREIGN KEY (activity_id) REFERENCES activities(id),
    CONSTRAINT fk_activity_registrations_user FOREIGN KEY (user_id) REFERENCES users(id)
);
